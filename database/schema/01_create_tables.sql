
-- Netflix Clone database schema
-- PostgreSQL

CREATE TABLE IF NOT EXISTS movies (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(200) NOT NULL,
    genre       VARCHAR(100) NOT NULL,
    year        INTEGER NOT NULL,
    rating      NUMERIC(3, 1) NOT NULL DEFAULT 7.0,
    poster      VARCHAR(2048) NOT NULL DEFAULT '',
    description TEXT NOT NULL DEFAULT '',
    CONSTRAINT chk_movies_year
        CHECK (year BETWEEN 1888 AND 2100),
    CONSTRAINT chk_movies_rating
        CHECK (rating BETWEEN 0 AND 10)
);

CREATE TABLE IF NOT EXISTS users (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    display_name  VARCHAR(100) NOT NULL,
    email         VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS watchlist (
    user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    movie_id   INTEGER NOT NULL REFERENCES movies(id) ON DELETE CASCADE,
    added_at   TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, movie_id)
);

CREATE TABLE IF NOT EXISTS viewing_events (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       INTEGER REFERENCES users(id) ON DELETE SET NULL,
    movie_id      INTEGER NOT NULL REFERENCES movies(id) ON DELETE CASCADE,
    event_type    VARCHAR(30) NOT NULL,
    progress_secs INTEGER NOT NULL DEFAULT 0,
    occurred_at   TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_viewing_event_type
        CHECK (event_type IN ('play', 'pause', 'complete', 'progress')),

    CONSTRAINT chk_progress_secs
        CHECK (progress_secs >= 0)
);
